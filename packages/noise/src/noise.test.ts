import { describe, expect, it } from 'vitest';
import { detectNoise } from './index.js';
import { type Change, makeInput } from './testutil.js';

const run = (changes: Change[]) => {
  const input = makeInput(changes);
  return { input, ...detectNoise(input) };
};
const kinds = (r: ReturnType<typeof run>) => Object.fromEntries([...r.hunkNoise].map(([id, n]) => [id, n.kind]));
const unformatted = `export function total(items: number[]) {
  let sum = 0
  for (let i = 0; i < items.length; i++) { sum += items[i] }
  return sum
}`;
const formatted = `export function total(items: number[]) {
  let sum = 0;
  for (let i = 0; i < items.length; i++) {
    sum += items[i];
  }
  return sum;
}`;

describe('lockfile', () => {
  it('collapses lockfile hunks (unverified) but not package.json', () => {
    const r = run([
      { path: 'pnpm-lock.yaml', before: 'a: 1\nb: 2', after: 'a: 1\nb: 3' },
      { path: 'packages/x/package-lock.json', before: '{"v":1}', after: '{"v":2}' },
      { path: 'package.json', before: '{\n  "dependencies": {"a": "1.0.0"}\n}', after: '{\n  "dependencies": {"a": "2.0.0"}\n}' },
    ]);
    expect(kinds(r)).toEqual({ 'hunk:pnpm-lock.yaml:0': 'lockfile', 'hunk:packages/x/package-lock.json:0': 'lockfile' });
    const g = r.collapsed.find((c) => c.id === 'collapsed:lockfile')!;
    expect(g.verified).toBe(false);
    expect(g.label).toBe('Lockfile updates (package-lock.json, pnpm-lock.yaml)');
  });
});

describe('generated', () => {
  it('matches path patterns and header markers, not ordinary files', () => {
    const r = run([
      { path: 'dist/app.js', before: 'a', after: 'b' },
      { path: 'src/api.pb.ts', before: 'a', after: 'b' },
      { path: 'src/__snapshots__/x.test.ts.snap', before: 'a', after: 'b' },
      { path: 'src/schema.ts', before: '// @generated by tool\nx', after: '// @generated by tool\ny' },
      { path: 'src/late.ts', before: 'a\nb\nc\nd\ne\n// DO NOT EDIT\nx', after: 'a\nb\nc\nd\ne\n// DO NOT EDIT\ny' },
      { path: 'src/real.ts', before: 'const a = 1', after: 'const a = 2' },
    ]);
    expect(Object.keys(kinds(r)).sort()).toEqual([
      'hunk:dist/app.js:0', 'hunk:src/__snapshots__/x.test.ts.snap:0', 'hunk:src/api.pb.ts:0', 'hunk:src/schema.ts:0',
    ]);
    expect(r.collapsed.find((c) => c.kind === 'generated')!.verified).toBe(false);
  });
});

describe('formatting', () => {
  it('prettier-style change is verified formatting', () => {
    const r = run([{ path: 'src/a.ts', before: unformatted, after: formatted.replace(/;$/gm, '') }]);
    // semicolons removed on both sides of the diff => token identical
    expect(kinds(r)).toEqual({ 'hunk:src/a.ts:0': 'formatting' });
    expect(r.collapsed[0]!.verified).toBe(true);
  });

  it('semicolon / quote / trailing comma changes are formatting but unverified', () => {
    const r = run([
      { path: 'src/a.ts', before: "const a = 'x'\nconst b = [1, 2]\nfoo(a, b)", after: 'const a = "x";\nconst b = [1, 2,];\nfoo(a, b);' },
    ]);
    expect(r.hunkNoise.get('hunk:src/a.ts:0')).toEqual({ kind: 'formatting', detail: 'punctuation/quote style' });
    expect(r.collapsed[0]!.verified).toBe(false);
  });

  it('reformat plus < to <= is NOT formatting', () => {
    const r = run([{ path: 'src/a.ts', before: unformatted, after: formatted.replace('i < items', 'i <= items') }]);
    expect(r.hunkNoise.size).toBe(0);
  });

  it('only the hunk with the real change survives a file with several hunks', () => {
    const pad = Array.from({ length: 12 }, (_, i) => `const k${i} = ${i}`).join('\n');
    const before = `const a = f(1,2)\n${pad}\nconst b = x<y`;
    const after = `const a = f(1, 2)\n${pad}\nconst b = x<=y`;
    const r = run([{ path: 'src/a.ts', before, after }]);
    expect(kinds(r)).toEqual({ 'hunk:src/a.ts:0': 'formatting' });
  });

  it('line breaks that matter (ASI) are not formatting', () => {
    const r = run([{ path: 'src/a.ts', before: 'function f(x: number) {\n  return\n  x\n}', after: 'function f(x: number) {\n  return x\n}' }]);
    expect(r.hunkNoise.size).toBe(0);
  });

  it('whitespace inside regex / strings / JSX text is not ignored', () => {
    expect(run([{ path: 'a.ts', before: 'const r = /a b/', after: 'const r = /ab/' }]).hunkNoise.size).toBe(0);
    expect(run([{ path: 'a.ts', before: 'const s = "a b"', after: 'const s = "ab"' }]).hunkNoise.size).toBe(0);
    expect(run([{ path: 'a.ts', before: 'const s = `a ${x} b`', after: 'const s = `a ${x}b`' }]).hunkNoise.size).toBe(0);
    expect(run([{ path: 'a.tsx', before: 'const e = <b>hello world</b>', after: 'const e = <b>helloworld</b>' }]).hunkNoise.size).toBe(0);
  });

  it('comment changes are real changes; unparseable files prove nothing', () => {
    expect(run([{ path: 'a.ts', before: 'const a = 1 // old', after: 'const a = 1 // new' }]).hunkNoise.size).toBe(0);
    expect(run([{ path: 'a.ts', before: 'const a = (1', after: 'const a = ( 1' }]).hunkNoise.size).toBe(0);
  });

  it('dropping a comma that is not trailing is not formatting', () => {
    expect(run([{ path: 'a.ts', before: 'const a = [1,,]', after: 'const a = [1,]' }]).hunkNoise.size).toBe(0);
  });

  it('non-JS text: whitespace-only is formatting, content change is not', () => {
    const r = run([
      { path: 'c.json', before: '{"a":1,"b":[1,2]}', after: '{\n  "a": 1,\n  "b": [1, 2]\n}' },
      { path: 'd.css', before: 'a{color:red}', after: 'a {\n  color:red\n}' },
      { path: 'e.json', before: '{"a":1}', after: '{\n  "a": 2\n}' },
      { path: 'f.py', before: 'if x:\n    y()', after: 'if x:\n  y()' },
    ]);
    expect(Object.keys(kinds(r))).toEqual([]); // single-line json cannot be matched line-wise: stays visible
    const r2 = run([
      { path: 'c.json', before: '{\n"a": 1,\n  "b": 2\n}', after: '{\n  "a": 1,\n  "b": 2\n}' },
      { path: 'g.md', before: 'hello  world\nfoo ', after: 'hello  world\nfoo' },
      { path: 'h.md', before: 'foo  ', after: 'foo' },
    ]);
    expect(kinds(r2)).toEqual({ 'hunk:c.json:0': 'formatting', 'hunk:g.md:0': 'formatting' });
    expect(r2.collapsed[0]!.verified).toBe(true);
  });
});

describe('rename', () => {
  it('pure rename without edits groups the file, verified', () => {
    const input = makeInput([{ path: 'src/new.ts', oldPath: 'src/old.ts', before: 'export const a = 1', after: 'export const a = 1' }]);
    const r = detectNoise(input);
    expect(r.hunkNoise.size).toBe(0);
    expect(r.collapsed).toHaveLength(1);
    expect(r.collapsed[0]).toMatchObject({ id: 'collapsed:rename', kind: 'rename', files: ['src/new.ts'], hunkIds: [], verified: true });
  });

  it('import path updates caused by a rename are noise; a different module is not', () => {
    const r = run([
      { path: 'src/lib/util.ts', oldPath: 'src/util.ts', before: 'export const u = 1', after: 'export const u = 1' },
      { path: 'src/a.ts', before: "import { u } from './util.js'\nuse(u)", after: "import { u } from './lib/util.js'\nuse(u)" },
      { path: 'src/b.ts', before: "import { u } from './util.js'\nuse(u)", after: "import { u } from './other.js'\nuse(u)" },
      { path: 'src/c.ts', before: "import { u } from 'pkg-a'\nuse(u)", after: "import { u } from 'pkg-b'\nuse(u)" },
    ]);
    expect(kinds(r)).toEqual({ 'hunk:src/a.ts:0': 'rename' });
    expect(r.hunkNoise.get('hunk:src/a.ts:0')!.detail).toBe('import path update');
    expect(r.collapsed[0]!.verified).toBe(true);
  });

  it('import update with another change on the same hunk is not rename', () => {
    const r = run([
      { path: 'src/lib/util.ts', oldPath: 'src/util.ts', before: 'export const u = 1', after: 'export const u = 1' },
      { path: 'src/a.ts', before: "import { u } from './util.js'\nuse(u)", after: "import { u } from './lib/util.js'\nuse(u + 1)" },
    ]);
    expect(r.hunkNoise.size).toBe(0);
  });

  it("moved file's own relative imports resolve to same module", () => {
    const r = run([
      { path: 'src/deep/a.ts', oldPath: 'src/a.ts', before: "import { z } from './z.js'\nz()", after: "import { z } from '../z.js'\nz()" },
    ]);
    expect(kinds(r)).toEqual({ 'hunk:src/deep/a.ts:0': 'rename' });
  });
});

describe('move', () => {
  const fn = (name: string) => `export function ${name}(a: number) {\n  const x = a * 2;\n  if (x > 10) {\n    return x;\n  }\n  return 0;\n}`;
  it('moved declarations across files are verified moves', () => {
    const r = run([
      { path: 'src/a.ts', before: `const keep = 1;\n\n${fn('calc')}\n\nconst tail = 2;`, after: 'const keep = 1;\n\nconst tail = 2;' },
      { path: 'src/b.ts', before: 'const head = 1;', after: `const head = 1;\n\n${fn('calc')}` },
    ]);
    expect(kinds(r)).toEqual({ 'hunk:src/a.ts:0': 'move', 'hunk:src/b.ts:0': 'move' });
    expect(r.collapsed[0]).toMatchObject({ id: 'collapsed:move', verified: true, files: ['src/a.ts', 'src/b.ts'] });
  });

  it('moved statements (not declarations) are unverified; short blocks are not moves', () => {
    const stmts = 'init();\nstep(1);\nstep(2);\nstep(3);\nfinish();';
    const r = run([
      { path: 'src/a.ts', before: `const a = 1;\n${stmts}\nconst z = 2;`, after: 'const a = 1;\nconst z = 2;' },
      { path: 'src/b.ts', before: 'const b = 1;', after: `const b = 1;\n${stmts}` },
    ]);
    expect(r.collapsed[0]).toMatchObject({ kind: 'move', verified: false });
    const short = run([
      { path: 'src/a.ts', before: 'const a = 1;\ninit();\nstep(1);\nconst z = 2;', after: 'const a = 1;\nconst z = 2;' },
      { path: 'src/b.ts', before: 'const b = 1;', after: 'const b = 1;\ninit();\nstep(1);' },
    ]);
    expect(short.hunkNoise.size).toBe(0);
  });

  it('a moved block with an extra edit on the other side is not a move', () => {
    const r = run([
      { path: 'src/a.ts', before: `const keep = 1;\n\n${fn('calc')}\n\nconst tail = 2;`, after: 'const keep = 1;\n\nconst tail = 2;' },
      { path: 'src/b.ts', before: 'const head = 1;', after: `const head = 1;\n\n${fn('calc').replace('x > 10', 'x >= 10')}` },
    ]);
    expect(r.hunkNoise.size).toBe(0);
  });

  it('in-place indentation change is not a move (formatting wins)', () => {
    const body = ['a();', 'b();', 'c();', 'd();', 'e();'];
    const r = run([{ path: 'src/a.ts', before: `function f() {\n${body.join('\n')}\n}`, after: `function f() {\n${body.map((l) => '  ' + l).join('\n')}\n}` }]);
    expect(kinds(r)).toEqual({ 'hunk:src/a.ts:0': 'formatting' });
  });
});

describe('mechanical', () => {
  const site = (i: number, call = 'oldName(value)') => `import { x } from './x.js';\nexport function f${i}(value: number) {\n  const a = 1;\n  return ${call};\n}`;
  const files = (n: number, outlierAt = -1): Change[] =>
    Array.from({ length: n }, (_, i) => ({
      path: `src/m${i}.ts`,
      before: site(i),
      after: site(i, i === outlierAt ? 'newName(value, true)' : 'newName(value)'),
    }));

  it('groups the same edit at many sites with exemplar and outliers', () => {
    const r = run(files(7, 3));
    const g = r.collapsed.find((c) => c.kind === 'mechanical')!;
    expect(g.id).toMatch(/^collapsed:mechanical:[0-9a-f]{8}$/);
    expect(g.hunkIds).toHaveLength(6);
    expect(g.verified).toBe(false);
    expect(g.exemplarHunkId).toBe('hunk:src/m0.ts:0');
    expect(g.outlierHunkIds).toEqual(['hunk:src/m3.ts:0']);
    expect(r.hunkNoise.has('hunk:src/m3.ts:0')).toBe(false);
    expect(g.label).toContain('`oldName`');
    expect(g.label).toContain('`newName`');
    expect(g.label).toContain('at 6 sites');
  });

  it('needs at least 5 hunks across at least 2 files', () => {
    expect(run(files(4)).hunkNoise.size).toBe(0);
    const one = makeInput([{
      path: 'src/one.ts',
      before: Array.from({ length: 8 }, (_, i) => `const a${i} = oldName(${i});\nconst pad${i} = 0;\nconst pad${i}b = 0;\nconst pad${i}c = 0;\nconst pad${i}d = 0;\nconst pad${i}e = 0;`).join('\n'),
      after: Array.from({ length: 8 }, (_, i) => `const a${i} = newName(${i});\nconst pad${i} = 0;\nconst pad${i}b = 0;\nconst pad${i}c = 0;\nconst pad${i}d = 0;\nconst pad${i}e = 0;`).join('\n'),
    }]);
    expect(one.hunks.length).toBeGreaterThanOrEqual(5);
    expect(detectNoise(one).hunkNoise.size).toBe(0);
  });

  it('abstracts varying identifiers into placeholders', () => {
    const r = run(Array.from({ length: 6 }, (_, i) => ({
      path: `src/w${i}.ts`, before: `const r = load${i};`, after: `const r = wrap(load${i});`,
    })));
    expect(r.collapsed.find((c) => c.kind === 'mechanical')?.hunkIds).toHaveLength(6);
  });
});

describe('priority, determinism, totals', () => {
  it('lockfile > generated > rename > move > formatting > mechanical', () => {
    const r = run([
      { path: 'dist/package-lock.json', before: 'a', after: 'b' }, // lockfile beats generated
      { path: 'dist/x.js', before: 'a', after: 'b' }, // generated beats everything below
      { path: 'src/f.ts', before: 'foo(oldName(1))', after: 'foo( newName(1) )' }, // not formatting
    ]);
    expect(r.hunkNoise.get('hunk:dist/package-lock.json:0')!.kind).toBe('lockfile');
    expect(r.hunkNoise.get('hunk:dist/x.js:0')!.kind).toBe('generated');
    expect(r.hunkNoise.has('hunk:src/f.ts:0')).toBe(false);
    // formatting hunks never become mechanical
    const fmt = run(Array.from({ length: 6 }, (_, i) => ({ path: `s/f${i}.ts`, before: 'foo(a,b)', after: 'foo(a, b)' })));
    expect(new Set(fmt.collapsed.map((c) => c.kind))).toEqual(new Set(['formatting']));
  });

  const mixed = (): Change[] => [
    { path: 'pnpm-lock.yaml', before: 'a: 1', after: 'a: 2' },
    { path: 'dist/o.js', before: 'x', after: 'y' },
    { path: 'src/a.ts', before: unformatted, after: formatted.replace(/;$/gm, '') },
    ...Array.from({ length: 6 }, (_, i) => ({ path: `src/m${i}.ts`, before: `export const v${i} = oldName(${i});`, after: `export const v${i} = newName(${i});` })),
  ];

  it('is deterministic regardless of input order', () => {
    const a = makeInput(mixed());
    const b = { ...a, hunks: [...a.hunks].reverse(), files: [...a.files].reverse() };
    const ra = detectNoise(a), rb = detectNoise(b);
    expect(rb.collapsed).toEqual(ra.collapsed);
    expect([...rb.hunkNoise].sort()).toEqual([...ra.hunkNoise].sort());
    expect(ra.collapsed.map((c) => c.kind)).toEqual(['lockfile', 'generated', 'formatting', 'mechanical']);
  });

  it('totals match member hunks and each hunk is in at most one group', () => {
    const input = makeInput(mixed());
    const r = detectNoise(input);
    const byId = new Map(input.hunks.map((h) => [h.id, h]));
    const seen = new Set<string>();
    for (const g of r.collapsed) {
      const hs = g.hunkIds.map((id) => byId.get(id)!);
      expect(g.added).toBe(hs.reduce((n, h) => n + h.added, 0));
      expect(g.removed).toBe(hs.reduce((n, h) => n + h.removed, 0));
      expect(g.files).toEqual([...new Set(hs.map((h) => h.path))].sort());
      for (const id of g.hunkIds) { expect(seen.has(id)).toBe(false); seen.add(id); expect(r.hunkNoise.get(id)!.kind).toBe(g.kind); }
    }
    expect(seen.size).toBe(r.hunkNoise.size);
  });
});

describe('property: mutating one token is never verified formatting', () => {
  it('holds for random snippets', () => {
    let seed = 7;
    const rnd = (n: number) => { seed = (seed * 1664525 + 1013904223) % 2 ** 32; return Math.floor((seed / 2 ** 32) * n); };
    const ids = ['a', 'b', 'count', 'items', 'x1'];
    const ops = ['+', '-', '*', '<', '>', '===', '&&', '||'];
    const stmt = (): string => {
      switch (rnd(4)) {
        case 0: return `const ${ids[rnd(5)]}${rnd(9)} = ${ids[rnd(5)]} ${ops[rnd(8)]} ${rnd(100)};`;
        case 1: return `if (${ids[rnd(5)]} ${ops[rnd(8)]} ${rnd(50)}) { call(${ids[rnd(5)]}, ${rnd(9)}); }`;
        case 2: return `out.push("${ids[rnd(5)]}", ${ids[rnd(5)]});`;
        default: return `let ${ids[rnd(5)]}${rnd(9)} = [${rnd(9)}, ${rnd(9)}];`;
      }
    };
    for (let iter = 0; iter < 150; iter++) {
      const lines = Array.from({ length: 3 + rnd(4) }, stmt);
      const before = lines.join('\n');
      // mutate exactly one token of one line, and also reflow whitespace on the same line
      const li = rnd(lines.length);
      const toks = lines[li]!.match(/[A-Za-z_]\w*|\d+|===|&&|\|\||[^\sA-Za-z_\d]/g)!;
      const ti = rnd(toks.length);
      const t = toks[ti]!;
      const repl = /^\d+$/.test(t) ? String(Number(t) + 1) : /^[A-Za-z_]/.test(t) ? t + 'Z' : ops.includes(t) ? ops[(ops.indexOf(t) + 1) % ops.length]! : null;
      if (repl === null) continue;
      toks[ti] = repl;
      const mutated = [...lines];
      mutated[li] = toks.join(' ');
      const r = run([{ path: 'src/p.ts', before, after: mutated.join('\n') }]);
      // when the mutated text does not even parse the result is also "not noise", which is what we assert
      for (const c of r.collapsed) expect(c.kind === 'formatting' && c.verified).toBe(false);
      for (const [, n] of r.hunkNoise) expect(n.kind).not.toBe('formatting');
    }
  });

  it('control: pure reflow of the same snippets is verified formatting', () => {
    const before = 'const a1 = b + 3;\nif (count < 5) { call(items, 2); }\nout.push("x", a);';
    const after = 'const a1   =  b+3 ;\nif (count<5) {\n  call(items,2);\n}\nout.push( "x" , a );';
    const r = run([{ path: 'src/p.ts', before, after }]);
    expect(r.collapsed[0]).toMatchObject({ kind: 'formatting', verified: true });
  });
});
